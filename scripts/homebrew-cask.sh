#!/bin/zsh
# 按打好的 dmg 生成 Homebrew cask，输出到 stdout。
#
#   scripts/homebrew-cask.sh <版本号> <dmg> > peerdeck.rb
#
# 本仓库自己就是 tap：release workflow 发布正式版以后，把结果提交成 Casks/peerdeck.rb。
# 那个文件是生成物，要改就改这里。第一次发版之前它不存在（还没有 dmg，算不出 sha256）。
# 环境变量：GITHUB_REPOSITORY（默认 xheiop/Peerdeck）。
set -euo pipefail

USAGE="用法：scripts/homebrew-cask.sh <版本号> <dmg>"
VERSION=${1:?$USAGE}
DMG=${2:?$USAGE}
REPO=${GITHUB_REPOSITORY:-xheiop/Peerdeck}
[[ $VERSION =~ '^[0-9]+\.[0-9]+\.[0-9]+$' ]] || { echo "cask 只给正式版用：$VERSION" >&2; exit 1; }
SHA=$(shasum -a 256 "$DMG" | cut -d' ' -f1)

# 不在 cask 里替用户去掉隔离属性（那等于静默绕过 Gatekeeper），只在 caveats 里告诉他怎么放行
cat <<RUBY
# Generated by scripts/homebrew-cask.sh on each release. Do not edit by hand.
cask "peerdeck" do
  version "$VERSION"
  sha256 "$SHA"

  url "https://github.com/$REPO/releases/download/v#{version}/Peerdeck-#{version}.dmg"
  name "Peerdeck"
  desc "Remote for qBittorrent and Transmission"
  homepage "https://github.com/$REPO"

  livecheck do
    url :url
    strategy :github_latest
  end

  depends_on macos: :sequoia

  app "Peerdeck.app"

  zap trash: [
    "~/Library/Application Support/Peerdeck",
    "~/Library/Caches/dev.peerdeck.mac",
    "~/Library/HTTPStorages/dev.peerdeck.mac",
    "~/Library/Preferences/dev.peerdeck.mac.plist",
    "~/Library/Saved Application State/dev.peerdeck.mac.savedState",
  ]

  caveats <<~EOS
    Peerdeck is ad-hoc signed and not notarized, so macOS blocks it on first launch.
    Open it once, then allow it in System Settings > Privacy & Security > Open Anyway.

    After an update macOS may ask again for access to the saved servers in your Keychain.
    Uninstalling, even with --zap, leaves that Keychain item ("Peerdeck Server Settings").
  EOS
end
RUBY
